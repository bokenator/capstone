"""
MACD + ATR Trailing Stop Strategy for vectorbt

Exports:
- compute_indicators: compute MACD, signal, ATR, SMA
- order_func: order function implementing MACD crossover entries and ATR-based trailing stops

Notes:
- No numba used.
- order_func returns simple Python tuples (size, size_type, direction) which are wrapped by the test harness.

Author: Generated by AI
"""
from typing import Any, Dict, Tuple

import numpy as np
import pandas as pd

import vectorbt as vbt
from vectorbt.portfolio.enums import SizeType, Direction

# Global state storage for order function contexts
_ORDER_FUNC_STATE: Dict[int, Dict[str, Any]] = {}


def compute_indicators(
    ohlcv: pd.DataFrame,
    macd_fast: int = 12,
    macd_slow: int = 26,
    macd_signal: int = 9,
    sma_period: int = 50,
    atr_period: int = 14,
) -> Dict[str, np.ndarray]:
    """
    Compute indicators required by the strategy.

    Args:
        ohlcv: DataFrame with columns ['open','high','low','close', ...]
        macd_fast: fast EMA period for MACD
        macd_slow: slow EMA period for MACD
        macd_signal: signal EMA period for MACD
        sma_period: period for trend SMA filter
        atr_period: ATR period

    Returns:
        Dictionary with numpy arrays for keys: 'close', 'high', 'macd', 'signal', 'atr', 'sma'
    """
    # Validate input columns
    required_cols = ["high", "low", "close"]
    for col in required_cols:
        if col not in ohlcv.columns:
            raise ValueError(f"ohlcv must contain '{col}' column")

    # Ensure numeric series
    close_s = ohlcv["close"].astype(float)
    high_s = ohlcv["high"].astype(float)
    low_s = ohlcv["low"].astype(float)

    # MACD: difference of EMAs
    # Use pandas ewm with adjust=False (standard EMA)
    fast_ema = close_s.ewm(span=macd_fast, adjust=False).mean()
    slow_ema = close_s.ewm(span=macd_slow, adjust=False).mean()
    macd_line = fast_ema - slow_ema
    signal_line = macd_line.ewm(span=macd_signal, adjust=False).mean()

    # 50-period SMA (trend filter)
    # Keep NaNs for initial warmup (min_periods = sma_period)
    sma = close_s.rolling(window=sma_period, min_periods=sma_period).mean()

    # ATR (Wilder's smoothing using ewm with alpha=1/period)
    prev_close = close_s.shift(1)
    tr1 = high_s - low_s
    tr2 = (high_s - prev_close).abs()
    tr3 = (low_s - prev_close).abs()
    true_range = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
    # Wilder's EMA
    atr = true_range.ewm(alpha=1.0 / atr_period, adjust=False).mean()

    # Convert to numpy arrays
    return {
        "close": close_s.to_numpy(dtype=float),
        "high": high_s.to_numpy(dtype=float),
        "macd": macd_line.to_numpy(dtype=float),
        "signal": signal_line.to_numpy(dtype=float),
        "atr": atr.to_numpy(dtype=float),
        "sma": sma.to_numpy(dtype=float),
    }


def order_func(
    c: Any,
    close: np.ndarray,
    high: np.ndarray,
    macd: np.ndarray,
    signal: np.ndarray,
    atr: np.ndarray,
    sma: np.ndarray,
    trailing_mult: float,
) -> Tuple[float, int, int]:
    """
    Order function implementing:
      - Entry: MACD crosses above signal AND price > 50 SMA
      - Exit: MACD crosses below signal OR price falls below (highest_since_entry - trailing_mult * ATR)

    Returns a tuple (size, size_type, direction). Use np.nan as size for no action.

    Notes on state:
    - We store minimal state in a module-level dict keyed by id(c) because the context object does not allow setting attributes.
    - We also attempt to read context-provided position attributes when available.
    """
    # Helper: safe index
    try:
        i = int(c.i)  # current integer index
    except Exception:
        # Fallback
        i = 0

    n = len(close)
    if i < 0 or i >= n:
        return (np.nan, SizeType.Amount, Direction.Both)

    # Use a module-level dict keyed by the context object's id
    ctx_id = id(c)
    if ctx_id not in _ORDER_FUNC_STATE:
        _ORDER_FUNC_STATE[ctx_id] = {"in_pos": False, "entry_idx": None, "highest": -np.inf}

    state = _ORDER_FUNC_STATE[ctx_id]

    # Utility: try to get current position size from context (if available)
    current_pos = 0.0
    for attr in ("pos", "position", "position_size", "size", "current_size"):
        if hasattr(c, attr):
            try:
                val = getattr(c, attr)
                current_pos = float(val) if val is not None else 0.0
                break
            except Exception:
                # ignore and continue
                pass

    # Prefer using context-provided position if available
    if current_pos > 0:
        state["in_pos"] = True
        # Try to read entry index from common attributes on context
        for attr in ("entry_i", "entry_idx", "entry_index"):
            if hasattr(c, attr):
                try:
                    entry_idx = int(getattr(c, attr))
                    state["entry_idx"] = entry_idx
                    # compute highest from recorded entry if possible
                    if 0 <= entry_idx <= i:
                        try:
                            state["highest"] = float(np.nanmax(high[entry_idx : i + 1]))
                        except Exception:
                            state["highest"] = float(high[i]) if not np.isnan(high[i]) else -np.inf
                    break
                except Exception:
                    pass

    # Update highest since entry if we are in a position
    if state["in_pos"]:
        try:
            if not np.isnan(high[i]):
                state["highest"] = max(state.get("highest", -np.inf), float(high[i]))
        except Exception:
            pass

    # Determine MACD cross up / down (require previous bar)
    cross_up = False
    cross_down = False
    if i > 0:
        if (
            not np.isnan(macd[i])
            and not np.isnan(signal[i])
            and not np.isnan(macd[i - 1])
            and not np.isnan(signal[i - 1])
        ):
            cross_up = (macd[i] > signal[i]) and (macd[i - 1] <= signal[i - 1])
            cross_down = (macd[i] < signal[i]) and (macd[i - 1] >= signal[i - 1])

    # Entry logic: only when not in a position
    if (not state["in_pos"]) and cross_up:
        # Price above SMA filter
        if not np.isnan(sma[i]) and not np.isnan(close[i]) and close[i] > sma[i]:
            size = 1.0
            state["in_pos"] = True
            state["entry_idx"] = i
            state["highest"] = float(high[i]) if not np.isnan(high[i]) else -np.inf
            # Use LongOnly if available, otherwise fall back to Both
            dir_long = getattr(Direction, "LongOnly", getattr(Direction, "LONG", getattr(Direction, "Long", Direction.Both)))
            return (float(size), SizeType.Amount, dir_long)

    # Exit logic: only when in a position
    if state["in_pos"]:
        # 1) MACD cross down -> exit
        if cross_down:
            exit_size = float(current_pos) if current_pos > 0 else 1.0
            state["in_pos"] = False
            state["entry_idx"] = None
            state["highest"] = -np.inf
            # Use Both for exit orders so selling is permitted
            return (exit_size, SizeType.Amount, Direction.Both)

        # 2) Trailing stop: price falls below (highest_since_entry - trailing_mult * ATR)
        if not np.isnan(atr[i]) and state.get("highest", -np.inf) != -np.inf:
            stop_level = state["highest"] - float(trailing_mult) * float(atr[i])
            if (not np.isnan(close[i])) and (close[i] < stop_level):
                exit_size = float(current_pos) if current_pos > 0 else 1.0
                state["in_pos"] = False
                state["entry_idx"] = None
                state["highest"] = -np.inf
                return (exit_size, SizeType.Amount, Direction.Both)

    # No action
    return (np.nan, SizeType.Amount, Direction.Both)
